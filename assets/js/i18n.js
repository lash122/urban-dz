let LANG = localStorage.getItem('ud_lang') || 'fr';
if (!I18N[LANG]) LANG = 'fr';

function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) || I18N.fr[key] || key;
}

/* t() with the exchange-window placeholder filled from dashboard settings */
function tx(key) {
  return t(key).replace(/\{d\}/g, window.EXCHANGE_DAYS || 7);
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  document.documentElement.dir = I18N[LANG].dir;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = tx(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  localStorage.setItem('ud_lang', lang);
  applyI18n();
  document.dispatchEvent(new CustomEvent('lang:changed'));
}
